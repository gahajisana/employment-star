// Regenerates app/i18n/glossary.ts from the EN-ID glossary CSV.
// Usage: npm run glossary [-- path/to/glossary.csv]
import { readFileSync, writeFileSync } from "node:fs";

import { buildPacks } from "../app/i18n/glossary-build.ts";

const source = process.argv[2] ?? "docs/Glossary - Sheet1.csv";
const target = "app/i18n/glossary.ts";

const { en, id, errors } = buildPacks(readFileSync(source, "utf8"));
if (errors.length) {
  console.error(`${source}: ${errors.length} problem(s)\n${errors.join("\n")}`);
  process.exit(1);
}

writeFileSync(
  target,
  `// GENERATED by \`npm run glossary\` from docs/Glossary - Sheet1.csv.
// Do not edit by hand: change the glossary, then rerun the script.
export const en = ${JSON.stringify(en, null, 2)} as const;

export type MessageKey = keyof typeof en;

export const id: Record<MessageKey, string> = ${JSON.stringify(id, null, 2)};
`,
);
console.log(`${target}: ${Object.keys(en).length} keys from ${source}`);
